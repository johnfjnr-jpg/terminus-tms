#!/usr/bin/env node
// Generates the ONE self-contained rollback for
// supabase/migrations/20261122000001_create_opportunity_from_any_visible_contact.sql
// (CREATE_FROM_ANY_CONTACT R2, the TERM_QUOTES M3 method).
//
//   node scripts/gen-create-from-any-contact-rollback.mjs           write the rollback file
//   node scripts/gen-create-from-any-contact-rollback.mjs --check   exit 1 if it is stale
//
// The rollback restores create_opportunity_from_contact, its comment and its
// grant EXACTLY as 20260908000003 left them. They are SLICED from that file at
// generation time and asserted byte-identical by
// scripts/tests/create-from-any-contact-rollback.test.mjs, never typed.
//
// R2's instance is why: the Phase 0 draft cut the restored comment at the
// first ";" after its start, which falls INSIDE the string ("caller must OWN
// the source Contact; a non-owner ..."), and produced an unterminated literal.
// The comment's end anchor here is "';", a quote closing the literal followed
// by the statement's own semicolon, and the pin test asserts the slice ends
// with the source's whole sentence.
//
// The slicer RAISES on an anchor it cannot find, or finds more than once,
// rather than returning a shorter file (Verification 12, the author's side).
// It is the TERM_QUOTES generator's slicer, imported, not a second copy
// (Verification 20).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { slice } from './gen-term-quotes-rollback.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const MIGRATION = '20261122000001'
export const ROLLBACK_PATH = `supabase/rollbacks/${MIGRATION}_create_opportunity_from_any_visible_contact.rollback.sql`
const SOURCE = 'supabase/migrations/20260908000003_create_from_requires_source_owner.sql'
const SIG = 'public.create_opportunity_from_contact(uuid, jsonb, text, numeric)'

export const BLOCKS = {
  FUNCTION: {
    source: SOURCE,
    start: 'create or replace function public.create_opportunity_from_contact(',
    end: '\n$$;',
  },
  COMMENT: {
    source: SOURCE,
    start: `comment on function ${SIG} is`,
    end: "';",
  },
  GRANT: {
    source: SOURCE,
    start: `grant execute on function ${SIG} to authenticated`,
    end: ';',
  },
}

export { slice }

export function extractBlocks(read = (p) => readFileSync(join(ROOT, p), 'utf8')) {
  const out = {}
  for (const [name, spec] of Object.entries(BLOCKS)) out[name] = slice(read(spec.source), spec, name)
  return out
}

export function renderRollback(read) {
  const b = extractBlocks(read)
  return `-- ROLLBACK of ${MIGRATION}_create_opportunity_from_any_visible_contact.sql
-- GENERATED by scripts/gen-create-from-any-contact-rollback.mjs. Do not edit by
-- hand: scripts/tests/create-from-any-contact-rollback.test.mjs fails on any
-- difference from the generator's output.
--
-- Restores create_opportunity_from_contact, its comment and its grant exactly
-- as ${SOURCE.split('/').pop()} left them: the source-owner
-- check and the audit_log row keyed on the contact come back.
--
-- Changes the function only. Opportunities created by non-owners while the
-- ruling was in force stay as they are, owned by their creators, with no audit
-- row on their contacts. Nothing to refuse on: no row depends on the function's
-- body.
--
-- Not parse-checked (Build discipline 14). Pasted as one file into the SQL
-- Editor; one transaction.

begin;

-- ── THE FUNCTION, AS ${SOURCE.split('/').pop()} LEFT IT ──

${b.FUNCTION}

${b.COMMENT}

${b.GRANT}

-- ── THE LEDGER ROW ───────────────────────────────────────────────────────

delete from supabase_migrations.schema_migrations where version = '${MIGRATION}';

notify pgrst, 'reload schema';

commit;
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderRollback()
  const path = join(ROOT, ROLLBACK_PATH)
  if (process.argv.includes('--check')) {
    const now = readFileSync(path, 'utf8')
    if (now !== text) { console.error(`${ROLLBACK_PATH} is stale: regenerate it`); process.exit(1) }
    console.log(`${ROLLBACK_PATH} is current (${Buffer.byteLength(text)} bytes)`)
  } else {
    writeFileSync(path, text)
    const back = readFileSync(path, 'utf8')
    if (back !== text) { console.error('written file does not read back identical'); process.exit(1) }
    console.log(`wrote ${ROLLBACK_PATH} (${Buffer.byteLength(text)} bytes)`)
  }
}
